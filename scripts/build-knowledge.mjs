#!/usr/bin/env node
// build-knowledge.mjs — assemble / verify / vendor the BKT knowledge base.
//
//   node scripts/build-knowledge.mjs build            -> regenerate knowledge/bkt-knowledge-bundle.md
//   node scripts/build-knowledge.mjs check [--strict] -> integrity gate
//   node scripts/build-knowledge.mjs sync --target <p> -> vendor `portable` entries into <p>/.knowledge-vendor/
//
// Hub = bkt-ai-apply. Knowledge flows one way: hub -> spoke. Freshness is tracked
// by a content hash of the bundle body (robust to commits), not the git SHA.

import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync, rmSync, copyFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join, resolve } from 'node:path'

const HUB = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const P = (...s) => join(HUB, ...s)
const log = (m) => console.log(m)
const sha256 = (b) => createHash('sha256').update(b).digest('hex')
const read = (p) => readFileSync(p, 'utf8')
const VALID_PORT = ['portable', 'hub-only', 'repo-scoped']

function hubSha() {
  try { return execFileSync('git', ['rev-parse', 'HEAD'], { cwd: HUB }).toString().trim() } catch { return 'unknown' }
}

// tiny frontmatter parser (no deps). Handles inline scalars, [..] arrays, and
// YAML block scalars (>, >-, |, |- ...) whose value spans indented lines.
function frontmatter(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---/)
  if (!m) return {}
  const fm = {}
  const lines = m[1].split('\n')
  for (let i = 0; i < lines.length; i++) {
    const mm = lines[i].match(/^([a-zA-Z_]+):\s*(.*)$/)
    if (!mm) continue
    let v = mm[2].trim()
    const block = v.match(/^([|>])[-+]?$/)
    if (block) {
      // gather following blank/more-indented lines as the scalar's body
      const body = []
      while (i + 1 < lines.length && (lines[i + 1].trim() === '' || /^\s/.test(lines[i + 1]))) {
        body.push(lines[++i].replace(/^\s+/, ''))
      }
      // folded (>) joins with spaces; literal (|) preserves newlines
      v = body.join(block[1] === '>' ? ' ' : '\n').trim()
    } else if (v.startsWith('[') && v.endsWith(']')) {
      v = v.slice(1, -1).split(',').map((s) => s.trim()).filter(Boolean)
    }
    fm[mm[1]] = v
  }
  return fm
}
const stripFm = (text) => text.replace(/^---\n[\s\S]*?\n---\n?/, '')

// ---- collectors -----------------------------------------------------------
function patterns() {
  const dir = P('knowledge', 'patterns')
  if (!existsSync(dir)) return []
  return readdirSync(dir).filter((f) => f.endsWith('.md')).sort()
    .map((f) => { const text = read(join(dir, f)); return { file: f, fm: frontmatter(text), text } })
}
function adrFiles() {
  const dir = P('docs', 'adr')
  if (!existsSync(dir)) return []
  return readdirSync(dir).filter((f) => /^\d+.*\.md$/.test(f)).sort()
}
function skillCatalog() {
  const dir = P('.agents', 'skills')
  if (!existsSync(dir)) return []
  return readdirSync(dir).sort().map((name) => {
    const p = join(dir, name, 'SKILL.md')
    if (!existsSync(p)) return null
    const fm = frontmatter(read(p))
    return { name, description: (fm.description || '').toString().slice(0, 160) }
  }).filter(Boolean)
}
function dupes(arr) { return [...new Set(arr.filter((v, i) => arr.indexOf(v) !== i))] }
function matchAll(text, re) { return [...text.matchAll(re)].map((m) => m[1]) }
function claudeRefPaths() {
  const t = read(P('CLAUDE.md'))
  return [...t.matchAll(/`(docs\/[^`]+\.md)`/g)].map((m) => m[1])
}

// ---- bundle body (shared by build + freshness check) ----------------------
function buildBody() {
  const out = []
  out.push('# BKT Knowledge Bundle')
  out.push('> Generated by `scripts/build-knowledge.mjs`. Upload to the Claude Web "BKT Memory" Project / Designer / Desktop. Do not hand-edit.')

  if (existsSync(P('docs/brand/positioning.md'))) {
    out.push('\n---\n\n## Brand Positioning\n\n' + stripFm(read(P('docs/brand/positioning.md'))).trim())
  }
  if (existsSync(P('docs/domain/business-rules.md'))) {
    out.push('\n---\n\n## Invariants (Business Rules)\n\n' + read(P('docs/domain/business-rules.md')).trim())
  }
  out.push('\n---\n\n## Decisions (ADR index)\n\n' + adrFiles().map((f) => `- ${f}`).join('\n'))
  out.push('\n---\n\n## Patterns\n\n' + patterns().map((p) => stripFm(p.text).trim()).join('\n\n---\n\n'))
  out.push('\n---\n\n## Skills catalog\n\n' + skillCatalog().map((s) => `- **${s.name}** — ${s.description}`).join('\n'))
  return out.join('\n') + '\n'
}

// ---- commands -------------------------------------------------------------
function doBuild() {
  const body = buildBody()
  const header = [
    '<!-- AUTO-GENERATED by scripts/build-knowledge.mjs — do not edit by hand -->',
    `<!-- hubSha: ${hubSha()} -->`,
    `<!-- sourcesHash: ${sha256(body)} -->`,
    '',
  ].join('\n')
  const out = P('knowledge', 'bkt-knowledge-bundle.md')
  writeFileSync(out, header + body)
  log(`✓ kb:build wrote ${out}`)
  log(`  ${patterns().length} patterns, ${adrFiles().length} ADRs, ${skillCatalog().length} skills, sourcesHash ${sha256(body).slice(0, 7)}`)
}

function doCheck({ strict }) {
  const problems = []
  // 1. pattern portability + id
  for (const p of patterns()) {
    if (!VALID_PORT.includes(p.fm.portability)) problems.push(`pattern ${p.file}: missing/invalid portability (${p.fm.portability ?? 'none'})`)
    if (!p.fm.id) problems.push(`pattern ${p.file}: missing id`)
  }
  // 2. duplicate IDs
  for (const d of dupes(adrFiles().map((f) => f.match(/^(\d+)/)[1]))) problems.push(`duplicate ADR id: ${d} (two files share NNN-)`)
  for (const d of dupes(patterns().map((p) => p.fm.id).filter(Boolean))) problems.push(`duplicate PAT id: ${d}`)
  if (existsSync(P('docs/domain/business-rules.md'))) {
    // only count DEFINITIONS (table rows `| BR-NNN | ... |`), not prose cross-references
    for (const d of dupes(matchAll(read(P('docs/domain/business-rules.md')), /^\|\s*BR-(\d+)\b/gm))) problems.push(`duplicate BR id: BR-${d}`)
  }
  if (existsSync(P('docs/retro/lessons.md'))) {
    for (const d of dupes(matchAll(read(P('docs/retro/lessons.md')), /^##\s*LSN-(\d+)/gm))) problems.push(`duplicate LSN id: LSN-${d}`)
  }
  // 3. CLAUDE.md reference paths resolve (skip template placeholders like NNN-description.md)
  for (const rel of claudeRefPaths()) {
    if (/NNN|\*/.test(rel)) continue
    if (!existsSync(P(rel))) problems.push(`CLAUDE.md reference path missing: ${rel}`)
  }
  // 4. bundle freshness (content hash, not git SHA)
  const bundle = P('knowledge', 'bkt-knowledge-bundle.md')
  if (existsSync(bundle)) {
    const m = read(bundle).match(/sourcesHash:\s*([0-9a-f]+)/)
    const cur = sha256(buildBody())
    if (m && m[1] !== cur) {
      const msg = 'bundle is stale — run pnpm kb:build'
      strict ? problems.push(msg) : log(`⚠ ${msg}`)
    }
  } else {
    log('⚠ no bundle yet — run pnpm kb:build')
  }

  if (problems.length) {
    log(`✗ kb:check FAILED (${problems.length})`)
    for (const p of problems) log(`  - ${p}`)
    process.exit(1)
  }
  log('✓ kb:check OK — unique IDs, valid portability, reference paths resolve')
}

function doSync(target) {
  if (!target) { console.error('ERROR: sync needs --target <path>'); process.exit(1) }
  const dest = resolve(process.cwd(), target)
  const vendor = join(dest, '.knowledge-vendor')
  const sha = hubSha()
  rmSync(join(vendor, 'patterns'), { recursive: true, force: true })
  mkdirSync(join(vendor, 'patterns'), { recursive: true })

  const portablePatterns = patterns().filter((p) => p.fm.portability === 'portable')
  for (const p of portablePatterns) copyFileSync(P('knowledge', 'patterns', p.file), join(vendor, 'patterns', p.file))

  const docs = []
  if (existsSync(P('docs/brand/positioning.md'))) {
    copyFileSync(P('docs/brand/positioning.md'), join(vendor, 'positioning.md')); docs.push('positioning.md')
  }

  const index = [
    '# Vendored BKT Knowledge (portable subset)',
    '',
    `> Vendored from \`bkt-ai-apply\` @ ${sha.slice(0, 7)} by \`build-knowledge.mjs\`.`,
    '> **Do not edit** — edit in the hub and re-run `pnpm kb:sync`. One way: hub → spoke.',
    '',
    '## Patterns',
    ...portablePatterns.map((p) => `- patterns/${p.file} — ${p.fm.title || p.fm.id}`),
    '',
    '## Docs',
    ...docs.map((d) => `- ${d}`),
    '',
  ].join('\n')
  writeFileSync(join(vendor, 'INDEX.md'), index)
  log(`✓ kb:sync → ${vendor}`)
  log(`  ${portablePatterns.length} portable patterns, ${docs.length} docs, hub @ ${sha.slice(0, 7)}`)
}

// ---- CLI ------------------------------------------------------------------
const argv = process.argv.slice(2)
const cmd = argv[0]
const strict = argv.includes('--strict')
const targetIdx = argv.indexOf('--target')
const target = targetIdx >= 0 ? argv[targetIdx + 1] : null

if (cmd === 'build') doBuild()
else if (cmd === 'check') doCheck({ strict })
else if (cmd === 'sync') doSync(target)
else { console.error('Usage: build-knowledge.mjs <build|check|sync> [--strict] [--target <path>]'); process.exit(1) }
